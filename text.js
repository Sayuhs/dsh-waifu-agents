/**
 * 宿主半边共享的那些小文本工具。
 *
 * `oneLine` 放在这里，是因为宿主半边一旦拆开就不止一个模块需要它：自更新
 * 的 feed 用它比较请求 id，面板 op 用它规整输入，而 `index.js` 用了它约 130
 * 次。一处定义、处处导入 —— 每个文件各抄一份，正是其中两份悄悄走样的方式。
 *
 * 与 `team.js` 的 `oneLine` 不是同一个函数：那个把每一段连续空白都折叠起来，
 * 且对任何不是字符串的东西回答 ""；这个保留一行内部的空格，并把拿到的任何
 * 东西字符串化。两者互不为超集，所以有意保持分开。
 */

/** 把一个值折叠到一行上，让它能在平铺的 front-matter 格式里存活。 */
export function oneLine(value) {
  return String(value ?? "")
    .replace(/\s*\r?\n\s*/g, " ")
    .trim();
}
